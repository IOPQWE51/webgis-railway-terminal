/** 计算某季节窗口下一次到来的峰值日期（YYYY-MM-DD）：若今年已过则自动顺延至明年 */
export function resolveNextPeakDate(peakMonth, peakDay, now = new Date()) {
  if (!Number.isInteger(peakMonth) || !Number.isInteger(peakDay)) return '';
  const y = now.getFullYear();
  const todayKey = `${y}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  const thisYearKey = `${y}-${String(peakMonth).padStart(2, '0')}-${String(peakDay).padStart(2, '0')}`;
  if (thisYearKey >= todayKey) return thisYearKey;
  return `${y + 1}-${String(peakMonth).padStart(2, '0')}-${String(peakDay).padStart(2, '0')}`;
}

/** 按出行月份（1~12 或 0=全部）、主题与搜索词筛选全球季节窗口 */
export function filterSeasonalWindows({ month = 0, theme = 'all', query = '' } = {}) {
  const q = String(query || '').trim().toLowerCase();
  return SEASONAL_WINDOWS.filter((w) => {
    if (month > 0 && !w.months.includes(month)) return false;
    if (theme && theme !== 'all' && w.theme !== theme) return false;
    if (!q) return true;
    return (
      w.name.toLowerCase().includes(q) ||
      w.country.toLowerCase().includes(q) ||
      w.region.toLowerCase().includes(q) ||
      w.railTip.toLowerCase().includes(q) ||
      w.photoTip.toLowerCase().includes(q)
    );
  });
}
